-- 1. TABLE COUNTS
SELECT 'CATEGORY' TABLE_NAME, COUNT(*) TOTAL FROM CATEGORY
UNION ALL
SELECT 'MEDICINE', COUNT(*) FROM MEDICINE
UNION ALL
SELECT 'SUPPLIER', COUNT(*) FROM SUPPLIER
UNION ALL
SELECT 'MEDICINE_SUPPLIER', COUNT(*) FROM MEDICINE_SUPPLIER
UNION ALL
SELECT 'INVENTORY', COUNT(*) FROM INVENTORY
UNION ALL
SELECT 'CUSTOMER', COUNT(*) FROM CUSTOMER
UNION ALL
SELECT 'EMPLOYEE', COUNT(*) FROM EMPLOYEE
UNION ALL
SELECT 'SALE', COUNT(*) FROM SALE
UNION ALL
SELECT 'SALE_DETAIL', COUNT(*) FROM SALE_DETAIL
UNION ALL
SELECT 'SYSTEM_SETTING', COUNT(*) FROM SYSTEM_SETTING;


-- 2. DATABASE OBJECTS
SELECT OBJECT_TYPE, COUNT(*) AS TOTAL
FROM USER_OBJECTS
WHERE OBJECT_TYPE IN (
    'TABLE', 'VIEW', 'PROCEDURE',
    'FUNCTION', 'TRIGGER', 'INDEX'
)
GROUP BY OBJECT_TYPE
ORDER BY OBJECT_TYPE;


-- 3. INVALID OBJECTS
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM USER_OBJECTS
WHERE STATUS = 'INVALID';


-- 4. CONSTRAINTS
SELECT CONSTRAINT_TYPE, STATUS, COUNT(*) AS TOTAL
FROM USER_CONSTRAINTS
WHERE CONSTRAINT_TYPE IN ('P', 'R', 'U', 'C')
GROUP BY CONSTRAINT_TYPE, STATUS
ORDER BY CONSTRAINT_TYPE;


-- 5. VIEWS
SELECT VIEW_NAME
FROM USER_VIEWS
ORDER BY VIEW_NAME;


-- 6. PROCEDURES AND FUNCTIONS
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM USER_OBJECTS
WHERE OBJECT_TYPE IN ('PROCEDURE', 'FUNCTION')
ORDER BY OBJECT_TYPE, OBJECT_NAME;


-- 7. TRIGGERS
SELECT TRIGGER_NAME, STATUS, TRIGGERING_EVENT
FROM USER_TRIGGERS
ORDER BY TRIGGER_NAME;


-- 8. INDEXES
SELECT INDEX_NAME, TABLE_NAME, STATUS
FROM USER_INDEXES
ORDER BY TABLE_NAME, INDEX_NAME;


