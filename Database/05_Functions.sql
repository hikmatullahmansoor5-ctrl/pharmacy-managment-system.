CREATE OR REPLACE EDITIONABLE FUNCTION "PHARMACY_MANAGEMENT"."GET_MEDICINE_PRICE" (
    P_M_ID IN NUMBER
)
RETURN NUMBER
AS
    V_PRICE NUMBER;
BEGIN
    SELECT PRICE
    INTO V_PRICE
    FROM MEDICINE
    WHERE M_ID = P_M_ID;

    RETURN V_PRICE;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;
END;
/



CREATE OR REPLACE EDITIONABLE FUNCTION "PHARMACY_MANAGEMENT"."GET_MEDICINE_STOCK" (
    P_M_ID IN NUMBER
)
RETURN NUMBER
AS
    V_STOCK NUMBER;
BEGIN
    SELECT NVL(SUM(QUANTITY), 0)
    INTO V_STOCK
    FROM INVENTORY
    WHERE MEDICINE_ID = P_M_ID
      AND EXPIRY_DATE >= TRUNC(SYSDATE);

    RETURN V_STOCK;
END;
/


CREATE OR REPLACE EDITIONABLE FUNCTION "PHARMACY_MANAGEMENT"."GET_TOTAL_SALES"
RETURN NUMBER
AS
    V_TOTAL NUMBER;
BEGIN
    SELECT NVL(SUM(TOTAL_AMOUNT), 0)
    INTO V_TOTAL
    FROM SALE;

    RETURN V_TOTAL;
END;
/


