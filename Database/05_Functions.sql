CREATE OR REPLACE EDITIONABLE FUNCTION "PHARMACY_MANAGEMENT"."GET_INVENTORY_VALUE"
RETURN NUMBER
AS
    V_VALUE NUMBER;
BEGIN
    SELECT NVL(SUM(QUANTITY * PURCHASE_PRICE), 0)
    INTO V_VALUE
    FROM INVENTORY
    WHERE EXPIRY_DATE >= TRUNC(SYSDATE);

    RETURN V_VALUE;
END;
/


CREATE OR REPLACE EDITIONABLE FUNCTION "PHARMACY_MANAGEMENT"."GET_SALE_TOTAL" (
    P_SALE_ID IN NUMBER
)
RETURN NUMBER
AS
    V_TOTAL NUMBER;
BEGIN
    SELECT NVL(SUM(SUBTOTAL), 0)
    INTO V_TOTAL
    FROM SALE_DETAIL
    WHERE SALE_ID = P_SALE_ID;

    RETURN V_TOTAL;
END;
