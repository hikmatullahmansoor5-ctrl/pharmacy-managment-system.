CREATE OR REPLACE FORCE EDITIONABLE VIEW "PHARMACY_MANAGEMENT"."CUSTOMER_REPORT_VIEW"
("CUSTOMER_ID", "CUSTOMER_NAME", "PHONE", "EMAIL", "TOTAL_SALES", "TOTAL_PURCHASE") AS
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.PHONE,
    C.EMAIL,
    COUNT(S.SALE_ID) AS TOTAL_SALES,
    NVL(SUM(S.TOTAL_AMOUNT), 0) AS TOTAL_PURCHASE
FROM CUSTOMER C
LEFT JOIN SALE S
    ON C.CUSTOMER_ID = S.CUSTOMER_ID
GROUP BY
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.PHONE,
    C.EMAIL;



    CREATE OR REPLACE FORCE EDITIONABLE VIEW "PHARMACY_MANAGEMENT"."EMPLOYEE_REPORT_VIEW"
("EMPLOYEE_ID", "EMPLOYEE_NAME", "JOB_TITLE", "PHONE", "SALARY", "TOTAL_SALES", "TOTAL_SALES_AMOUNT") AS
SELECT
    E.EMPLOYEE_ID,
    E.EMPLOYEE_NAME,
    E.JOB_TITLE,
    E.PHONE,
    E.SALARY,
    COUNT(S.SALE_ID) AS TOTAL_SALES,
    NVL(SUM(S.TOTAL_AMOUNT), 0) AS TOTAL_SALES_AMOUNT
FROM EMPLOYEE E
LEFT JOIN SALE S
    ON E.EMPLOYEE_ID = S.EMPLOYEE_ID
GROUP BY
    E.EMPLOYEE_ID,
    E.EMPLOYEE_NAME,
    E.JOB_TITLE,
    E.PHONE,
    E.SALARY;



    CREATE OR REPLACE FORCE EDITIONABLE VIEW "PHARMACY_MANAGEMENT"."EXPIRY_REPORT_VIEW"
("INVENTORY_ID", "M_NAME", "BATCH_NUMBER", "QUANTITY", "EXPIRY_DATE", "EXPIRY_STATUS") AS
SELECT
    I.INVENTORY_ID,
    M.M_NAME,
    I.BATCH_NUMBER,
    I.QUANTITY,
    I.EXPIRY_DATE,
    CASE
        WHEN I.EXPIRY_DATE < TRUNC(SYSDATE)
            THEN 'EXPIRED'
        WHEN I.EXPIRY_DATE <= TRUNC(SYSDATE) + 90
            THEN 'EXPIRING SOON'
        ELSE 'VALID'
    END AS EXPIRY_STATUS
FROM INVENTORY I
JOIN MEDICINE M
    ON I.MEDICINE_ID = M.M_ID;




    CREATE OR REPLACE FORCE EDITIONABLE VIEW "PHARMACY_MANAGEMENT"."INVENTORY_REPORT_VIEW"
("INVENTORY_ID", "M_NAME", "SUPPLIER_NAME", "BATCH_NUMBER", "QUANTITY", "PURCHASE_PRICE", "EXPIRY_DATE", "RECEIVED_DATE", "STOCK_VALUE") AS
SELECT
    I.INVENTORY_ID,
    M.M_NAME,
    S.S_NAME AS SUPPLIER_NAME,
    I.BATCH_NUMBER,
    I.QUANTITY,
    I.PURCHASE_PRICE,
    I.EXPIRY_DATE,
    I.RECEIVED_DATE,
    I.QUANTITY * I.PURCHASE_PRICE AS STOCK_VALUE
FROM INVENTORY I
JOIN MEDICINE M
    ON I.MEDICINE_ID = M.M_ID
JOIN SUPPLIER S
    ON I.SUPPLIER_ID = S.S_ID;



    CREATE OR REPLACE FORCE EDITIONABLE VIEW "PHARMACY_MANAGEMENT"."LOW_STOCK_VIEW"
("M_ID", "M_NAME", "TOTAL_STOCK", "LOW_STOCK_LIMIT") AS
SELECT
    M.M_ID,
    M.M_NAME,
    SUM(I.QUANTITY) AS TOTAL_STOCK,
    SS.LOW_STOCK_LIMIT
FROM MEDICINE M
JOIN INVENTORY I
    ON M.M_ID = I.MEDICINE_ID
CROSS JOIN SYSTEM_SETTING SS
WHERE I.EXPIRY_DATE >= TRUNC(SYSDATE)
GROUP BY
    M.M_ID,
    M.M_NAME,
    SS.LOW_STOCK_LIMIT
HAVING SUM(I.QUANTITY) <= SS.LOW_STOCK_LIMIT;



CREATE OR REPLACE FORCE EDITIONABLE VIEW "PHARMACY_MANAGEMENT"."MEDICINE_STOCK_VIEW"
("M_ID", "M_NAME", "GENERIC_NAME", "STRENGTH", "CATEGORY_NAME", "PRICE", "TOTAL_STOCK") AS
SELECT
    M.M_ID,
    M.M_NAME,
    M.GENERIC_NAME,
    M.STRENGTH,
    C.C_NAME AS CATEGORY_NAME,
    M.PRICE,
    NVL(SUM(
        CASE
            WHEN I.EXPIRY_DATE >= TRUNC(SYSDATE)
            THEN I.QUANTITY
            ELSE 0
        END
    ), 0) AS TOTAL_STOCK
FROM MEDICINE M
JOIN CATEGORY C
    ON M.CATEGORY_ID = C.C_ID
LEFT JOIN INVENTORY I
    ON M.M_ID = I.MEDICINE_ID
GROUP BY
    M.M_ID,
    M.M_NAME,
    M.GENERIC_NAME,
    M.STRENGTH,
    C.C_NAME,
    M.PRICE;


    CREATE OR REPLACE FORCE EDITIONABLE VIEW "PHARMACY_MANAGEMENT"."SALES_REPORT_VIEW"
("SALE_ID", "CUSTOMER_NAME", "EMPLOYEE_NAME", "SALE_DATE", "TOTAL_AMOUNT") AS
SELECT
    S.SALE_ID,
    C.CUSTOMER_NAME,
    E.EMPLOYEE_NAME,
    S.SALE_DATE,
    S.TOTAL_AMOUNT
FROM SALE S
LEFT JOIN CUSTOMER C
    ON S.CUSTOMER_ID = C.CUSTOMER_ID
JOIN EMPLOYEE E
    ON S.EMPLOYEE_ID = E.EMPLOYEE_ID;
    