CREATE TABLE CATEGORY (
    C_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    C_NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),

    CONSTRAINT PK_CATEGORY PRIMARY KEY (C_ID),
    CONSTRAINT UQ_CATEGORY_NAME UNIQUE (C_NAME)
);

CREATE TABLE MEDICINE (
    M_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    M_NAME VARCHAR2(150) NOT NULL,
    GENERIC_NAME VARCHAR2(150),
    STRENGTH VARCHAR2(50),
    DOSAGE_FORM VARCHAR2(50),
    PRICE NUMBER(10,2) NOT NULL,
    CATEGORY_ID NUMBER NOT NULL,
    DESCRIPTION VARCHAR2(500),

    CONSTRAINT PK_MEDICINE PRIMARY KEY (M_ID),
    CONSTRAINT FK_MEDICINE_CATEGORY
        FOREIGN KEY (CATEGORY_ID)
        REFERENCES CATEGORY(C_ID),
    CONSTRAINT CK_MEDICINE_PRICE CHECK (PRICE >= 0)
);



CREATE TABLE supplier (
    s_id NUMBER PRIMARY KEY,
    s_name VARCHAR2(100) NOT NULL,
    address VARCHAR2(255),
    phone VARCHAR2(20)
);



CREATE TABLE MEDICINE_SUPPLIER (
    MS_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    MEDICINE_ID NUMBER NOT NULL,
    SUPPLIER_ID NUMBER NOT NULL,

    CONSTRAINT PK_MEDICINE_SUPPLIER
        PRIMARY KEY (MS_ID),

    CONSTRAINT FK_MS_MEDICINE
        FOREIGN KEY (MEDICINE_ID)
        REFERENCES MEDICINE(M_ID),

    CONSTRAINT FK_MS_SUPPLIER
        FOREIGN KEY (SUPPLIER_ID)
        REFERENCES SUPPLIER(S_ID),

    CONSTRAINT UQ_MEDICINE_SUPPLIER
        UNIQUE (MEDICINE_ID, SUPPLIER_ID)
);


CREATE TABLE INVENTORY (
    INVENTORY_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    MEDICINE_ID NUMBER NOT NULL,
    SUPPLIER_ID NUMBER NOT NULL,
    BATCH_NUMBER VARCHAR2(100) NOT NULL,
    EXPIRY_DATE DATE NOT NULL,
    QUANTITY NUMBER NOT NULL,
    PURCHASE_PRICE NUMBER(10,2) NOT NULL,
    RECEIVED_DATE DATE DEFAULT SYSDATE,

    CONSTRAINT PK_INVENTORY
        PRIMARY KEY (INVENTORY_ID),

    CONSTRAINT FK_INVENTORY_MED_SUP
        FOREIGN KEY (MEDICINE_ID, SUPPLIER_ID)
        REFERENCES MEDICINE_SUPPLIER
        (MEDICINE_ID, SUPPLIER_ID),

    CONSTRAINT UQ_INVENTORY_BATCH
        UNIQUE (MEDICINE_ID, BATCH_NUMBER),

    CONSTRAINT CK_INVENTORY_QUANTITY
        CHECK (QUANTITY >= 0),

    CONSTRAINT CK_INVENTORY_PRICE
        CHECK (PURCHASE_PRICE >= 0)
);


CREATE TABLE CUSTOMER (
    CUSTOMER_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    CUSTOMER_NAME VARCHAR2(150) NOT NULL,
    PHONE VARCHAR2(30) NOT NULL,
    EMAIL VARCHAR2(150),
    ADDRESS VARCHAR2(250),
    CREATED_DATE DATE DEFAULT SYSDATE,

    CONSTRAINT PK_CUSTOMER
        PRIMARY KEY (CUSTOMER_ID),

    CONSTRAINT UQ_CUSTOMER_PHONE
        UNIQUE (PHONE)
);

CREATE TABLE EMPLOYEE (
    EMPLOYEE_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    EMPLOYEE_NAME VARCHAR2(150) NOT NULL,
    GENDER VARCHAR2(10),
    PHONE VARCHAR2(30) NOT NULL,
    EMAIL VARCHAR2(150),
    ADDRESS VARCHAR2(250),
    JOB_TITLE VARCHAR2(100) NOT NULL,
    SALARY NUMBER(10,2) NOT NULL,
    HIRE_DATE DATE DEFAULT SYSDATE,

    CONSTRAINT PK_EMPLOYEE
        PRIMARY KEY (EMPLOYEE_ID),

    CONSTRAINT UQ_EMPLOYEE_PHONE
        UNIQUE (PHONE),

    CONSTRAINT CK_EMPLOYEE_GENDER
        CHECK (GENDER IN ('Male', 'Female')),

    CONSTRAINT CK_EMPLOYEE_SALARY
        CHECK (SALARY >= 0)
);


CREATE TABLE SALE (
    SALE_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    CUSTOMER_ID NUMBER,
    EMPLOYEE_ID NUMBER NOT NULL,
    SALE_DATE DATE DEFAULT SYSDATE,
    TOTAL_AMOUNT NUMBER(12,2) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_SALE
        PRIMARY KEY (SALE_ID),

    CONSTRAINT FK_SALE_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER(CUSTOMER_ID),

    CONSTRAINT FK_SALE_EMPLOYEE
        FOREIGN KEY (EMPLOYEE_ID)
        REFERENCES EMPLOYEE(EMPLOYEE_ID),

    CONSTRAINT CK_SALE_TOTAL
        CHECK (TOTAL_AMOUNT >= 0)
);


CREATE TABLE SALE_DETAIL (
    SALE_DETAIL_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    SALE_ID NUMBER NOT NULL,
    INVENTORY_ID NUMBER NOT NULL,
    QUANTITY NUMBER NOT NULL,
    UNIT_PRICE NUMBER(10,2) NOT NULL,
    SUBTOTAL NUMBER(12,2) NOT NULL,

    CONSTRAINT PK_SALE_DETAIL
        PRIMARY KEY (SALE_DETAIL_ID),

    CONSTRAINT FK_SD_SALE
        FOREIGN KEY (SALE_ID)
        REFERENCES SALE(SALE_ID),

    CONSTRAINT FK_SD_INVENTORY
        FOREIGN KEY (INVENTORY_ID)
        REFERENCES INVENTORY(INVENTORY_ID),

    CONSTRAINT CK_SD_QUANTITY
        CHECK (QUANTITY > 0),

    CONSTRAINT CK_SD_UNIT_PRICE
        CHECK (UNIT_PRICE >= 0),

    CONSTRAINT CK_SD_SUBTOTAL
        CHECK (SUBTOTAL >= 0),

    CONSTRAINT UQ_SALE_INVENTORY
        UNIQUE (SALE_ID, INVENTORY_ID)
);


CREATE TABLE SYSTEM_SETTING (
    SETTING_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    LOW_STOCK_LIMIT NUMBER DEFAULT 10 NOT NULL,
    UPDATED_AT DATE DEFAULT SYSDATE,

    CONSTRAINT PK_SYSTEM_SETTING
        PRIMARY KEY (SETTING_ID),

    CONSTRAINT CK_LOW_STOCK_LIMIT
        CHECK (LOW_STOCK_LIMIT >= 0)
);

